import { expect, helpers, test } from './fixtures'

test('deposit → worker sees phone → shift confirmed → both review → reputation shown', async ({ page: p }) => {
  const h = helpers(p)
  await p.goto('/app'); await h.see('Phụ bếp ca tối')
  await h.asEmployer()
  await h.openApplicants('Pha chế ca sáng'); await h.see('Minh Anh'); await h.see('Mới')
  await p.getByRole('button', { name: 'Nhận', exact: true }).click(); await h.see('Chốt'); await p.getByRole('button', { name: 'Xong' }).click()
  await h.see('Nạp tiền giữ chỗ để người làm thấy'); await h.noHScroll()
  await p.getByRole('button', { name: 'Nạp tiền giữ chỗ' }).click(); await h.see('Giữ tiền công cho ca này'); await h.see('Chế độ thử'); await h.see('Người làm nhận')
  const hours = p.getByLabel('Tổng số giờ làm dự kiến')
  await hours.fill('10'); await h.see('280.000đ')
  await hours.fill('0'); await expect(p.getByRole('button', { name: 'Xác nhận nạp tiền' })).toBeDisabled()
  await hours.fill('10'); await h.see('280.000đ')
  await p.getByRole('button', { name: 'Xác nhận nạp tiền' }).click(); await h.see('Đã giữ 280.000đ')
  await h.signOut()
  await h.asSeeker(); await h.see('đã được giữ an toàn'); await h.see('0900 000 002'); await h.noHScroll()
  await h.signOut()
  await h.asEmployer(); await h.openApplicants('Pha chế ca sáng')
  await p.getByRole('button', { name: 'Xác nhận đã làm xong' }).click(); await h.see('Người làm đã đến chưa?')
  await p.getByRole('button', { name: /Đến đủ ca/ }).click(); await h.see('Đánh giá người làm')
  await p.getByRole('radio', { name: '5' }).click(); await p.getByRole('button', { name: 'Chăm chỉ' }).click(); await p.getByPlaceholder('Nhận xét ngắn').fill('Làm tốt, đúng giờ')
  await p.getByRole('button', { name: 'Gửi đánh giá' }).click(); await h.see('Đã đánh giá')
  await h.go('/app/tai-khoan'); await h.section('Đánh giá về bạn'); await h.see('Chưa có đánh giá nào được hiển thị')
  await h.signOut()
  await h.asSeeker(); await h.see('Ca đã xong'); await h.see('chưa đánh giá'); await h.see('Bên kia đã đánh giá bạn')
  await p.getByRole('button', { name: 'Đánh giá', exact: true }).click(); await h.see('Đánh giá quán')
  await p.getByRole('radio', { name: '4' }).click(); await p.getByRole('button', { name: 'Thân thiện' }).click(); await p.getByRole('button', { name: 'Gửi đánh giá' }).click(); await h.see('Đã đánh giá')
  await h.go('/app/tai-khoan'); await h.section('Đánh giá về bạn'); await h.see('Làm tốt, đúng giờ'); await h.see('Ca hoàn thành'); await h.see('100%'); await h.noHScroll()
  await h.go('/app/viec-lam'); await expect(p.locator('button.job', { hasText: 'Pha chế ca sáng' }).first().getByText('1 ca xong')).toBeVisible()
  await p.locator('button.job', { hasText: 'Pha chế ca sáng' }).first().click(); await h.see('Quán Cà Phê Dùng Thử'); await h.see('4.0')
})

test('no-show reported → worker agrees → refund, recorded on worker reputation', async ({ page: p }) => {
  const h = helpers(p)
  await p.goto('/app'); await h.see('Phụ bếp ca tối')
  await h.asEmployer(); await h.postJob('Ca thử vắng', true); await h.signOut()
  await h.go('/app'); await p.locator('button.job', { hasText: 'Ca thử vắng' }).first().click(); await p.getByRole('button', { name: 'Ứng tuyển ngay' }).first().click()
  await p.getByRole('button', { name: 'Dùng thử: Người tìm việc' }).click(); await h.see('Đã gửi đơn!'); await h.signOut()
  await h.asEmployer(); await h.openApplicants('Ca thử vắng'); await h.see('Minh Anh')
  await p.getByRole('button', { name: 'Nhận', exact: true }).click(); await p.getByRole('button', { name: 'Xong' }).click()
  await p.getByRole('button', { name: 'Nạp tiền giữ chỗ' }).click(); await p.getByRole('button', { name: 'Xác nhận nạp tiền' }).click(); await h.see('Đã giữ')
  await p.getByRole('button', { name: 'Xác nhận đã làm xong' }).click(); await p.getByRole('button', { name: /Không đến/ }).click(); await h.see('Chờ họ phản hồi')
  await h.signOut()
  await h.asSeeker(); await h.see('Quán báo bạn không đến')
  await p.getByRole('button', { name: 'Đúng, tôi không đến' }).click(); await h.see('hoàn tiền cho quán')
  await h.go('/app/tai-khoan'); await h.see('Lần vắng'); await expect(p.locator('.tiles .bad').getByText('1')).toBeVisible()
})
